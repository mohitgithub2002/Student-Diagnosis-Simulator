const DICTS: Record<Lang, Dict> = { en, hi, hinglish };

export function t(lang: Lang | string, key: string, vars: Record<string, string | number> = {}): string {
  const dict = DICTS[(lang as Lang) in DICTS ? (lang as Lang) : "en"];
  const template = dict[key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export const LANGUAGE_NAMES: Record<Lang, string> = { en: "English", hi: "हिंदी", hinglish: "Hinglish" };

export function missingKeys(lang: Lang): string[] {
  return Object.keys(en).filter((k) => !(k in DICTS[lang]));
}
